/**
 * Telco-focused opportunity scoring algorithm.
 * A company scores >80 (High Priority 🔥) if:
 * - Sector is 'salud', 'logistica', or 'servicios'
 * - Employee count > 40
 * - Detected needs include 'Seguridad' or 'Conectividad'
 */
export const calculateTelcoScore = (company: Partial<Company>): number => {
  const employees = company.employees || 0;
  const sector = company.sector || '';
  const needs = company.detectedNeeds || [];
  
  // Base points
  let score = 0;
  
  // Employee size (max 25)
  score += employees >= 250 ? 25 : employees >= 100 ? 20 : employees >= 50 ? 15 : employees >= 40 ? 12 : 8;
  
  // Sector priority (max 20) — salud, logistica, servicios are high-value telco sectors
  const highPrioritySectors = ['salud', 'logistica', 'servicios'];
  const medPrioritySectors = ['industria', 'turismo'];
  score += highPrioritySectors.includes(sector) ? 20 : medPrioritySectors.includes(sector) ? 15 : 10;
  
  // Detected needs: security & connectivity (max 20)
  const hasSecurityNeed = needs.some(n => n.toLowerCase().includes('seguridad') || n.toLowerCase().includes('security'));
  const hasConnectivityNeed = needs.some(n => n.toLowerCase().includes('conectividad') || n.toLowerCase().includes('connectivity') || n.toLowerCase().includes('backup'));
  score += (hasSecurityNeed ? 10 : 0) + (hasConnectivityNeed ? 10 : 0);
  
  // Digitalization gap opportunity (max 15)
  score += company.digitalizationLevel === 'bajo' ? 15 : company.digitalizationLevel === 'medio' ? 10 : 5;
  
  // Growth signals (max 10)
  score += Math.min(10, (company.growthSignals?.length || 0) * 4);
  
  // Multi-site bonus (max 10)
  score += company.isMultiSite ? 10 : 0;
  
  return Math.min(100, score);
};

const generateScoreBreakdown = (company: Partial<Company>): ScoreBreakdownItem[] => {
  const employeePoints = company.employees! >= 250 ? 20 : company.employees! >= 100 ? 15 : company.employees! >= 50 ? 10 : 5;
  const sectorPoints = ['industria', 'logistica', 'turismo', 'salud', 'servicios'].includes(company.sector!) ? 15 : 10;
  const digiPoints = company.digitalizationLevel === 'bajo' ? 15 : company.digitalizationLevel === 'medio' ? 10 : 5;
  const growthPoints = (company.growthSignals?.length || 0) * 5;
  const multiSitePoints = company.isMultiSite ? 10 : 0;
  const arpuPoints = Math.min(20, Math.floor(company.estimatedARPU! / 300));

  return [
    { factor: 'Tamaño empresa', points: employeePoints, maxPoints: 20, description: `${company.employees} empleados` },
    { factor: 'Sector prioritario', points: sectorPoints, maxPoints: 15, description: company.sector! },
    { factor: 'Nivel digitalización', points: digiPoints, maxPoints: 15, description: company.digitalizationLevel! },
    { factor: 'Señales crecimiento', points: Math.min(20, growthPoints), maxPoints: 20, description: `${company.growthSignals?.length || 0} señales` },
    { factor: 'Multi-sede', points: multiSitePoints, maxPoints: 10, description: company.isMultiSite ? 'Sí' : 'No' },
    { factor: 'ARPU potencial', points: arpuPoints, maxPoints: 20, description: `€${company.estimatedARPU}/mes` },
  ];
};

