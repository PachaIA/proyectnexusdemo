export const getCompanyById = (id: string): Company | undefined => {
  return companies.find(c => c.id === id);
};

export const filterCompanies = (
  sectorFilter: string[],
  employeeFilter: string[],
  locationFilter: string[],
  opportunityFilter?: string[],
  digitalizationFilter?: string[]
): Company[] => {
  return companies.filter(company => {
    const sectorMatch = sectorFilter.length === 0 || sectorFilter.includes(company.sector);
    
    const employeeMatch = employeeFilter.length === 0 || employeeFilter.some(range => {
      const rangeData = employeeRanges.find(r => r.id === range);
      if (!rangeData) return false;
      return company.employees >= rangeData.min && company.employees <= rangeData.max;
    });
    
    const locationMatch = locationFilter.length === 0 || locationFilter.includes(company.locationType);
    
    const opportunityMatch = !opportunityFilter || opportunityFilter.length === 0 || opportunityFilter.some(level => {
      const levelData = opportunityLevels.find(l => l.id === level);
      if (!levelData) return false;
      if (level === 'alta') return company.opportunityScore >= 80;
      if (level === 'media') return company.opportunityScore >= 60 && company.opportunityScore < 80;
      return company.opportunityScore < 60;
    });
    
    const digitalizationMatch = !digitalizationFilter || digitalizationFilter.length === 0 || 
      digitalizationFilter.includes(company.digitalizationLevel);
    
    return sectorMatch && employeeMatch && locationMatch && opportunityMatch && digitalizationMatch;
  });
};
